"use strict";

// The commit-msg hook: mechanical enforcement of a real commit-message format
// (Conventional Commits), same "mechanical wall > prose" philosophy as
// `ai-learn guard` — but a git-native hook, not a Claude PreToolUse hook, so
// it lives in its own file rather than growing guard.js further.
//
// Installed via `core.hooksPath=.githooks` (a tracked, versioned directory),
// not `.git/hooks/` — `.git/hooks` is local-only and never travels with a
// clone, the same reason this repo's own `.githooks/pre-push` exists. Only
// `ai-learn init`/`update` ever write here (trusted, internal `spawnGit`
// calls) — this is never something the AI's own Bash tool could run itself,
// since `ai-learn guard` (see guard.js) blocks the AI from invoking `git`
// at all.

const fs = require("fs");
const path = require("path");
const { spawnGit } = require("./util");

const TEMPLATES_DIR = path.join(__dirname, "..", "..", "templates");

// The exact prefix `templates/commit-msg` starts with — marks a hook file as
// generated by ai-learn (safe to refresh) vs. customized by the learner
// (never touched), same pattern as codex-guard.js's MARKER and the solutions
// README's title check in guard.js.
const MARKER = "#!/usr/bin/env sh\n# generated by ai-learn — commit-msg hook (Conventional Commits).";

// Mirrors the shell PATTERN in templates/commit-msg — used by check.js to
// detect commits that slipped past the hook (a `--no-verify` bypass, or a
// project where the hook was never wired in the first place).
const CONVENTIONAL_COMMITS_RE =
  /^(feat|fix|docs|style|refactor|perf|test|build|ci|chore|revert)(\([a-zA-Z0-9._-]+\))?!?: .{1,72}/;

function gitConfigGet(dir, key) {
  try {
    const res = spawnGit(["-C", dir, "config", "--get", key], { encoding: "utf8" });
    return res.status === 0 ? res.stdout.trim() : null;
  } catch {
    return null;
  }
}

function templateContent() {
  return fs.readFileSync(path.join(TEMPLATES_DIR, "commit-msg"), "utf8");
}

// Writes/refreshes `.githooks/commit-msg` and wires `core.hooksPath` to it —
// best-effort, mirrors `gitState()` in scan.js: no `.git` yet (very common at
// `init` time, before the learner's first `git init`) is a silent no-op,
// picked up automatically the next time `ai-learn update` runs, no manual
// step for anyone to remember. A pre-existing, differently-configured
// `core.hooksPath` is never clobbered.
function ensureCommitMsgHook(dir) {
  if (!fs.existsSync(path.join(dir, ".git"))) {
    return { skipped: "no-git-repo" };
  }

  const hooksDir = path.join(dir, ".githooks");
  const hookFile = path.join(hooksDir, "commit-msg");
  const content = templateContent();
  const existing = fs.existsSync(hookFile) ? fs.readFileSync(hookFile, "utf8") : null;
  const isGenerated = existing === null || existing.startsWith(MARKER);

  let file = "kept";

  if (isGenerated && existing !== content) {
    fs.mkdirSync(hooksDir, { recursive: true });
    fs.writeFileSync(hookFile, content);
    try {
      fs.chmodSync(hookFile, 0o755);
    } catch {
      // best-effort — no-op on platforms without unix permission bits
    }
    file = existing === null ? "created" : "refreshed";
  }

  const current = gitConfigGet(dir, "core.hooksPath");

  if (current === ".githooks" || current === "./.githooks") {
    return { file, hooksPath: "already-set" };
  }
  if (current) {
    return { file, hooksPath: "customized", existing: current };
  }

  spawnGit(["-C", dir, "config", "core.hooksPath", ".githooks"], { encoding: "utf8" });
  return { file, hooksPath: "set" };
}

// Best-effort wiring check for `check.js` — mirrors the existing "guard not
// wired" warning shape. `null` means "not applicable yet" (no `.git`), so the
// caller can skip the warning entirely rather than nag a project that hasn't
// run `git init` yet.
function commitMsgHookWired(dir) {
  if (!fs.existsSync(path.join(dir, ".git"))) {
    return null;
  }
  if (!fs.existsSync(path.join(dir, ".githooks", "commit-msg"))) {
    return false;
  }
  const current = gitConfigGet(dir, "core.hooksPath");
  return current === ".githooks" || current === "./.githooks";
}

module.exports = { ensureCommitMsgHook, commitMsgHookWired, CONVENTIONAL_COMMITS_RE, MARKER };
