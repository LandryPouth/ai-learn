"use strict";

// Codex CLI mechanical guard: a `.codex/config.toml` permissions profile that
// denies write access to the learner's files (src/** by default) at the OS
// sandbox level (Landlock/bwrap on Linux, Seatbelt on macOS) — not a hook, a
// kernel-enforced filesystem restriction, active whether Codex writes via
// apply_patch or a Bash redirection.
//
// Verified empirically with `codex sandbox --permissions-profile ai-learn-guard
// -- <cmd>` (codex-cli 0.138.0, Linux/bwrap): a write into a denied path fails
// with EPERM regardless of the writing technique (shell redirection, a Python
// `open().write()`), while the rest of the workspace stays writable. NOT yet
// verified inside a live interactive Codex session with real model calls —
// only the sandbox enforcement layer itself, via the `codex sandbox` debug
// harness (no model call, no auth required).
//
// A custom `default_permissions` profile REPLACES Codex's built-in
// workspace-write grants entirely — omitting a broad read grant ("/" = "read")
// breaks Codex's own ability to exec itself inside the sandbox (hit this
// empirically on the first attempt). This profile restates it.
//
// Project config (<project>/.codex/config.toml) is only loaded by Codex for a
// "trusted" project — the learner approves that once, the same one-time
// prompt Codex already shows for any project config.

const PROFILE_NAME = "ai-learn-guard";
const MARKER = "# generated by ai-learn — see AGENTS.md §3 (do not hand-edit; re-run `ai-learn update` after changing .ai-learn/guard.json)";

function denyEntries(learnerFiles) {
  const entries = new Set();

  for (const glob of learnerFiles) {
    entries.add(glob);
    if (glob.endsWith("/**")) {
      entries.add(glob.slice(0, -3));
    }
  }

  return [...entries];
}

function renderConfig(learnerFiles) {
  const deny = denyEntries(learnerFiles)
    .map((glob) => `"${glob}" = "deny"`)
    .join("\n");

  return `${MARKER}

default_permissions = "${PROFILE_NAME}"

[permissions.${PROFILE_NAME}]
description = "ai-learn: workspace write, except the learner's own files"

[permissions.${PROFILE_NAME}.filesystem]
"/" = "read"

[permissions.${PROFILE_NAME}.filesystem.":workspace_roots"]
"." = "write"
${deny}
`;
}

module.exports = { renderConfig, PROFILE_NAME, MARKER };
