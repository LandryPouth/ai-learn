"use strict";

// Codex CLI mechanical guard: a `.codex/config.toml` permissions profile that
// denies write access to the learner's files (src/** by default) at the OS
// sandbox level (Landlock/bwrap on Linux, Seatbelt on macOS) — not a hook, a
// kernel-enforced filesystem restriction, active whether Codex writes via
// apply_patch or a Bash redirection.
//
// Verified empirically with `codex sandbox --permissions-profile ai-learn-guard
// -- <cmd>` (codex-cli 0.138.0, Linux/bwrap): a write into a denied path fails
// with EPERM regardless of the writing technique (shell redirection, a Python
// `open().write()`), while the rest of the workspace stays writable. NOT yet
// verified inside a live interactive Codex session with real model calls —
// only the sandbox enforcement layer itself, via the `codex sandbox` debug
// harness (no model call, no auth required).
//
// A custom `default_permissions` profile REPLACES Codex's built-in
// workspace-write grants entirely — omitting a broad read grant ("/" = "read")
// breaks Codex's own ability to exec itself inside the sandbox (hit this
// empirically on the first attempt). This profile restates it.
//
// Project config (<project>/.codex/config.toml) is only loaded by Codex for a
// "trusted" project — the learner approves that once, the same one-time
// prompt Codex already shows for any project config.
//
// Limite connue (vérifiée sur codex-cli 0.138.0) : les clés de
// `filesystem.":workspace_roots"` sont des chemins littéraux, pas des globs —
// `src` et `src/a.ts` refusent l'écriture, `src/**` ou `**/*.test.ts` sont
// ignorés. `denyEntries` n'émet donc **que** des chemins littéraux. Émettre à la
// fois `src/**` et `src` casse même le démarrage de bwrap dès que `src` contient
// un fichier existant (`Can't create file ...: Read-only file system`), donc la
// forme glob est supprimée, pas seulement « inertée ».
//
// En mode `dirigeant`, les répertoires de test existants sont ajoutés par
// `ensureGuardHook` (`src/test`, `src/__tests__`, …) ; un répertoire créé après
// la génération ou un test colocalisé (`src/*.test.ts`) reste écrivable par le
// sandbox OS — le hook Claude les bloque. C'est une limite du modèle Codex
// (clés littérales), pas une omission silencieuse.

const fs = require("fs");
const path = require("path");

const PROFILE_NAME = "ai-learn-guard";
const MARKER = "# generated by ai-learn — see AGENTS.md §3 (do not hand-edit; re-run `ai-learn update` after changing .ai-learn/guard.json)";

// Files/dirs that wire the guard itself. The sandbox grants `"." = "write"`, so
// without these a Codex session could rewrite its own permission profile, the
// `guard.json` that `ai-learn update` later renders it from, or the Claude hook
// settings (`.claude/settings*.json`, e.g. `{"disableAllHooks": true}`) that
// disable the other platform's guard. Literal paths, same as the other Codex
// filesystem keys; directories are denied too so `rm -rf .ai-learn` cannot drop
// the policy through its parent.
const PROTECTED_PATHS = [
  ".ai-learn",
  ".ai-learn/guard.json",
  ".codex",
  ".codex/config.toml",
  ".claude",
  ".claude/settings.json",
  ".claude/settings.local.json",
];
const GLOB_CHARS = /[*?[\]{}]/;
const TEST_DIR_NAMES = new Set(["test", "tests", "__tests__", "checkpoint"]);
// Directories that never hold the project's own test suite; descending into
// them would deny an unrelated `build/test` (and waste the scan budget).
const SKIP_DIR_NAMES = new Set([
  "node_modules",
  ".git",
  ".codex",
  ".ai-learn",
  ".claude",
  "dist",
  "build",
  "out",
  "target",
  "vendor",
  "coverage",
  ".next",
  ".cache",
  ".turbo",
  ".venv",
  "venv",
]);
const MAX_SCAN_DIRS = 1000;

// Codex filesystem keys are literal paths. A `dir/**` pattern contributes its
// literal directory; a pattern containing any other glob character contributes
// nothing (emitting it would be inert at best, and the duplicate `dir/**` key
// is what aborts bwrap).
function literalDenyPath(value) {
  if (typeof value !== "string" || !value) {
    return null;
  }

  if (value.endsWith("/**")) {
    const base = value.slice(0, -3);
    return base && !GLOB_CHARS.test(base) ? base : null;
  }

  return GLOB_CHARS.test(value) ? null : value;
}

function denyEntries(learnerFiles, extraPaths = []) {
  const entries = new Set(PROTECTED_PATHS);

  for (const value of [...learnerFiles, ...extraPaths]) {
    const literal = literalDenyPath(value);
    if (literal) {
      entries.add(literal);
    }
  }

  return [...entries];
}

// Existing nested test directories are the only ones Codex can deny literally
// (new directories and colocated files need globs, which the sandbox ignores).
// Walk the project once, skipping the usual noise, and return POSIX paths.
function findLiteralTestDirs(root) {
  const found = new Set();
  let visited = 0;

  const walk = (current, rel) => {
    if (visited >= MAX_SCAN_DIRS) {
      return;
    }
    visited += 1;

    let entries;
    try {
      entries = fs.readdirSync(current, { withFileTypes: true });
    } catch {
      return;
    }

    for (const entry of entries) {
      if (!entry.isDirectory()) {
        continue;
      }

      const name = entry.name.toLowerCase();
      if (SKIP_DIR_NAMES.has(name)) {
        continue;
      }

      const childRel = rel ? `${rel}/${entry.name}` : entry.name;
      if (TEST_DIR_NAMES.has(name)) {
        found.add(childRel);
      }
      walk(path.join(current, entry.name), childRel);
    }
  };

  walk(root, "");
  return [...found].sort();
}

function renderConfig(learnerFiles, extraPaths = []) {
  const deny = denyEntries(learnerFiles, extraPaths)
    .map((entry) => `${JSON.stringify(entry)} = "deny"`)
    .join("\n");

  return `${MARKER}

# Codex filesystem keys are literal paths, not globs (codex-cli 0.138.0): only
# the exact file/directory paths below are enforced. Glob keys are omitted —
# they are inert, and a duplicate "dir/**" + "dir" pair aborts bwrap when dir
# already contains a file. Existing nested test dirs are listed; newly created
# dirs and colocated test files remain writable at the sandbox level — the
# Claude PreToolUse hook is the guard for those.

default_permissions = "${PROFILE_NAME}"

[permissions.${PROFILE_NAME}]
description = "ai-learn: workspace write, except the learner's own files"

[permissions.${PROFILE_NAME}.filesystem]
"/" = "read"

[permissions.${PROFILE_NAME}.filesystem.":workspace_roots"]
"." = "write"
${deny}
`;
}

module.exports = { renderConfig, denyEntries, findLiteralTestDirs, PROFILE_NAME, MARKER };
