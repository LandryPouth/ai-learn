"use strict";

// Wiring of the `ai-learn guard` into OpenCode. Claude Code runs a shell hook
// declared in .claude/settings.json; Codex gets an OS-sandbox profile; OpenCode
// has no such file — it loads plugins from .opencode/plugins/ and exposes
// `tool.execute.before`, where a `throw` refuses the call. The generated plugin
// (templates/opencode-guard-plugin.js) translates an OpenCode tool call into the
// PreToolUse payload `decide` already understands and throws on its denial;
// `decide` itself is untouched.
//
// Same non-destructive contract as the other guards: a first-line marker
// identifies a file ai-learn wrote, so `init`/`update` regenerate it freely and
// leave a plugin the learner wrote alone. `inspectOpenCodeGuard` gives `check`
// the same current/stale/foreign/absent states as the norm hook.

const fs = require("fs");
const path = require("path");

const TEMPLATES_DIR = path.join(__dirname, "..", "..", "..", "templates");
const PLUGIN_TEMPLATE = path.join(TEMPLATES_DIR, "opencode-guard-plugin.js");

const PLUGIN_RELATIVE = path.join(".opencode", "plugins", "ai-learn-guard.js");

// First line of the file, and how we recognise it as ours. A plugin carrying
// this marker is regenerated freely; one without it is the learner's and is
// left alone.
const MARKER = "// ai-learn:guard-plugin";

// The binary the plugin runs. Same choice as the Claude hook: the absolute path
// of this checkout's entry point, so no `npx` runs on every write.
const TOOL_BIN = path.join(__dirname, "..", "..", "ai-learn.js");

// OpenCode is "in use" when the project already carries its config or plugin
// directory. We never create .opencode/ for someone who does not use it —
// `--platform opencode` is the explicit opt-in.
function usesOpenCode(root = process.cwd()) {
  return ["opencode.json", "opencode.jsonc", ".opencode"].some((name) => fs.existsSync(path.join(root, name)));
}

function pluginSource({ binary = TOOL_BIN } = {}) {
  const body = fs
    .readFileSync(PLUGIN_TEMPLATE, "utf8")
    .replace("__BINARY__", () => JSON.stringify(binary));

  return `${MARKER} — generated by \`ai-learn init\`/\`update\`; remove this line to keep your own\n${body}`;
}

function isOurs(source) {
  if (typeof source !== "string") {
    return false;
  }
  // Exact first line (plus the generated suffix), so `// ai-learn:guard-plugin-old`
  // is a foreign file, not something `update` may overwrite.
  const first = source.split("\n", 1)[0];
  return first === MARKER || first.startsWith(`${MARKER} `) || first.startsWith(`${MARKER}\t`);
}

function pluginPath(root = process.cwd()) {
  return path.join(root, PLUGIN_RELATIVE);
}

// Statuses: "created", "upgraded" (ours, regenerated), "unchanged", "skipped"
// (not ours, or OpenCode is not in use and `force` was not passed).
function ensureOpenCodeGuard(root = process.cwd(), { dryRun = false, force = false, binary } = {}) {
  if (!force && !usesOpenCode(root)) {
    return { status: "skipped", path: null };
  }

  const target = pluginPath(root);
  const next = pluginSource(binary ? { binary } : {});
  const existed = fs.existsSync(target);

  if (existed) {
    let current;

    try {
      current = fs.readFileSync(target, "utf8");
    } catch {
      // A directory or an unreadable file at the plugin path: leave it alone and
      // let `check` report it, instead of crashing init/update.
      return { status: "skipped", path: target, unreadable: true };
    }

    if (!isOurs(current)) {
      return { status: "skipped", path: target };
    }
    if (current === next) {
      return { status: "unchanged", path: target };
    }
  }

  if (!dryRun) {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, next);
  }

  return { status: existed ? "upgraded" : "created", path: target };
}

// What `check` reads back: present + ours + current. "absent" is only a problem
// when OpenCode is in use; a stale file is ours but was written by an older
// ai-learn (or hand-edited), and a foreign one is the learner's.
function inspectOpenCodeGuard(root = process.cwd(), { binary } = {}) {
  const target = pluginPath(root);

  if (!fs.existsSync(target)) {
    return { state: "absent", path: target };
  }

  let current;

  try {
    current = fs.readFileSync(target, "utf8");
  } catch {
    return { state: "unreadable", path: target };
  }

  if (!isOurs(current)) {
    return { state: "foreign", path: target };
  }

  return {
    state: current === pluginSource(binary ? { binary } : {}) ? "current" : "stale",
    path: target,
  };
}

module.exports = {
  ensureOpenCodeGuard,
  inspectOpenCodeGuard,
  usesOpenCode,
  pluginSource,
  PLUGIN_RELATIVE,
  MARKER,
};
