"use strict";

// `ai-learn update [--root <dir>]` — propagate the current protocol template and
// the traps bank to every installed learning project under a root.
//
// The protocol (AGENTS-apprentissage.md) and the friction bank both evolve in
// the tool; the copies living in each project would otherwise go stale. `update`
// re-syncs them everywhere at once.
//
// Non-destructive by design, mirroring `init`: an AGENTS.md is only overwritten
// when it is a *generated* file — i.e. it carries the protocol title marker. A
// customized AGENTS.md is never touched; it gets the protocol in
// docs/plans/mode-apprentissage.md instead. progress.json is never modified.

const fs = require("fs");
const path = require("path");
const os = require("os");
const { log, findLearningProjects, normalizePortable } = require("./util");
const { readProgress, scaffoldState, stampToolVersion } = require("./progress");
const { regenerateTraps } = require("./traps");
const { ensureGuardHook } = require("./guard");
const { ensureOpenCodeGuard, usesOpenCode, PLUGIN_RELATIVE } = require("./platforms/opencode-guard");
const { ensureCommitMsgHook } = require("./git-hooks");
const { ensureGitignore } = require("./gitignore");
const { ensureNormConfig, ensureNormHook } = require("./norm");
const { ensureMutateConfig } = require("./mutate");
const {
  ensurePredictionsFile,
  journalPath: predictionsJournalPath,
} = require("./predictions");
const { detectDomainKey } = require("./tracks/domain");
const { syncProjectLedgers, formatSyncFailure, ledgerHealth } = require("./ledgers");
const { PLATFORMS, INSTALLERS } = require("./install");
const {
  ensureNativeMemoryFile,
  detectedPlatforms,
  NATIVE_MEMORY_FILE,
} = require("./platforms/ensure");

const TEMPLATES_DIR = path.join(__dirname, "..", "..", "templates");

// One `### <severity> — <title>` heading per recorded entry — same marker
// check.js's countDogfoodEntries uses. Duplicated locally rather than
// imported: check.js pulls in progress/status/docs, too heavy to require here
// for one regex.
function hasDogfoodEntries(content) {
  return /^###\s+(?:low|medium|high)\s+—/im.test(content);
}

// Backfill the friction journal into a project that predates it, and refresh
// it when the template evolves — but only while it is still pristine (no
// entries yet). Once an agent has logged real friction, the file is never
// touched again, same non-destructive stance as ensureGuardHook. Returns
// "created", "refreshed", or "kept".
function syncDogfood(dir) {
  const dogfoodFile = path.join(dir, ".ai-learn", "dogfood.md");
  const template = fs.readFileSync(
    path.join(TEMPLATES_DIR, "dogfood.md"),
    "utf8",
  );

  if (fs.existsSync(dogfoodFile)) {
    const existing = fs.readFileSync(dogfoodFile, "utf8");

    if (hasDogfoodEntries(existing)) {
      return "kept";
    }
    if (existing === template) {
      return "kept";
    }

    fs.writeFileSync(dogfoodFile, template);
    return "refreshed";
  }

  fs.mkdirSync(path.dirname(dogfoodFile), { recursive: true });
  fs.writeFileSync(dogfoodFile, template);
  return "created";
}

// Backfill the checkpoint/ orientation stub into a project that predates it
// (`init` scaffolded checkpoint/ empty before this template existed). Never
// overwritten once present — same non-destructive stance as the rest of this
// file; a learner may have edited or replaced it.
function syncCheckpointReadme(dir) {
  const readmePath = path.join(dir, "checkpoint", "README.md");

  if (fs.existsSync(readmePath)) {
    return "kept";
  }

  fs.mkdirSync(path.dirname(readmePath), { recursive: true });
  fs.writeFileSync(
    readmePath,
    fs.readFileSync(path.join(TEMPLATES_DIR, "checkpoint-readme.md"), "utf8"),
  );
  return "created";
}

// Backfill .ai-learn/predictions.json into a project that predates story
// 01.03 (see bin/lib/predictions.js). Locked decision: once this file
// exists and is valid, it is the source of truth for counting — even over a
// non-empty legacy docs/plans/predictions.md, which is why this flags that
// case explicitly instead of backfilling silently.
function syncPredictionsData(dir) {
  const result = ensurePredictionsFile(dir);

  if (!result.created) {
    return { action: "kept" };
  }

  const journal = predictionsJournalPath(dir);
  const hasLegacyEntries =
    fs.existsSync(journal) &&
    /^###\s+Phase\s+\d+\s+[—–-]\s+prédiction/im.test(
      fs.readFileSync(journal, "utf8"),
    );

  return { action: "created", hasLegacyEntries };
}

// The exact title `init` writes as the first line of a generated AGENTS.md. Its
// presence marks the file as generated by ai-learn — the only AGENTS.md `update`
// may overwrite.
const PROTOCOL_MARKER =
  "Instructions pour les agents IA — projet d'apprentissage";

function templateContent() {
  return fs.readFileSync(
    path.join(TEMPLATES_DIR, "AGENTS-apprentissage.md"),
    "utf8",
  );
}

// Place the protocol in a project the same way `init` does, except that a
// generated AGENTS.md is *refreshed* rather than kept. Returns
// `{ file, action }` for the per-project report.
function syncProtocol(dir, config) {
  const content = templateContent().replace(
    /\{\{technology\}\}/g,
    config.technology || "votre techno",
  );
  const rootAgents = path.join(dir, "AGENTS.md");
  const modeApprentissage = path.join(
    dir,
    "docs",
    "plans",
    "mode-apprentissage.md",
  );

  if (fs.existsSync(rootAgents)) {
    if (fs.readFileSync(rootAgents, "utf8").includes(PROTOCOL_MARKER)) {
      fs.writeFileSync(rootAgents, content);
      return { file: "AGENTS.md", action: "refreshed" };
    }

    // A customized AGENTS.md — never overwrite it.
    fs.mkdirSync(path.dirname(modeApprentissage), { recursive: true });
    fs.writeFileSync(modeApprentissage, content);
    return { file: "docs/plans/mode-apprentissage.md", action: "written" };
  }

  fs.writeFileSync(rootAgents, content);
  return { file: "AGENTS.md", action: "created" };
}

// A learner who continues an existing project on a *different* platform than
// the one it was `init`ed on (Claude Code → Codex, say) has the per-project
// mechanical guards already in place (ensureGuardHook wires both
// unconditionally, regardless of platform) but not that new platform's
// global /… commands — those are only ever installed on request. Passing
// --platform here (the calling agent knows its own identity, same as
// `init`) self-heals that: idempotent, safe to run every session. Never
// guessed — an unrecognized platform string is a warning, not a failure.
function ensurePlatformCommands(platform) {
  if (!platform) {
    return null;
  }

  if (!PLATFORMS[platform]) {
    log(
      `  ⚠ plateforme "${platform}" inconnue — skills non installés (voir \`ai-learn install\`)`,
    );
    return null;
  }

  try {
    const result = INSTALLERS[platform]({ home: os.homedir() });
    return { platform, created: result.created.length, removed: result.removed.length + result.retired.length, retiredFiles: result.retired, kept: result.kept.length + result.keptModified.length, keptFiles: result.kept.concat(result.keptModified) };
  } catch (error) {
    log(
      `  ⚠ installation des skills ${platform} a échoué : ${error.message}`,
    );
    return null;
  }
}

function updateCommand({ root, platform, home }) {
  const projects = findLearningProjects(root);

  if (projects.length === 0) {
    log(`No learning projects (no progress.json) under ${root}.`);
    return;
  }

  const platformResult = ensurePlatformCommands(platform);

  if (platformResult) {
    log(
      `Platform ${platformResult.platform}: skills synchronisés (${platformResult.created} fichier(s) créé/rafraîchi, ${platformResult.removed} ancien(s) retiré(s), ${platformResult.kept} conservé(s)).`,
    );

    for (const file of platformResult.retiredFiles) {
      log(`  − ${file}`);
    }

    for (const file of platformResult.keptFiles) {
      log(`  = ${file}`);
    }
  }

  log(`Updating ${projects.length} learning project(s) under ${root}:`);

  for (const project of projects) {
    const { config, exists } = readProgress(project);

    if (!exists || !config) {
      log(`\n${path.basename(project)}`);
      log("  ⚠ progress.json invalid — skipped");
      continue;
    }

    const protocol = syncProtocol(project, config);
    const stamped = stampToolVersion(project);
    const stampLine = stamped
      ? null
      : `  ⚠ ce projet vient d'une version plus récente de l'outil (${scaffoldState(config).toolVersion}) — rien n'est rétrogradé, mets l'outil à jour`;

    // Native memory backfill (story 04.01). With no --platform, every platform
    // that needs a stub AND is installed on this machine gets one: `update`
    // walks projects globally and cannot know which agent opens each, but an
    // installed platform is the signal `check` uses too — no stray GEMINI.md
    // for a Claude-only learner.
    // With an explicit --platform, only that platform's stub is ensured — and
    // none at all for Codex/OpenCode, which read AGENTS.md natively.
    const nativePlatforms = platform
      ? [platform]
      : detectedPlatforms().filter((name) => NATIVE_MEMORY_FILE[name]);
    const nativeMemory = nativePlatforms
      .map((name) => ensureNativeMemoryFile(project, name))
      .filter(Boolean);

    const { traps } = regenerateTraps(project);
    const guard = ensureGuardHook(project);
    // OpenCode's guard plugin (story 08.01): only for a project that uses
    // OpenCode, or when the caller explicitly says it does.
    const openCodeGuard =
      usesOpenCode(project) || platform === "opencode"
        ? ensureOpenCodeGuard(project, { force: platform === "opencode" })
        : null;
    // claude-code is the only platform with a PostToolUse hook; an explicit
    // other --platform wires nothing (AGENTS.md §3quater documents the fallback).
    const normHook = !platform || platform === "claude" ? ensureNormHook(project) : null;
    const dogfood = syncDogfood(project);
    const checkpointReadme = syncCheckpointReadme(project);
    const commitHook = ensureCommitMsgHook(project);
    const gitignore = ensureGitignore(project);

    // Same real-detected-language sourcing as init.js — see there for why
    // this is not the free-text progress.json `technology` label.
    let detectedLanguage = null;
    try {
      detectedLanguage = detectDomainKey(project).stack.language;
    } catch {
      // best-effort — falls back to generic defaults
    }
    const normConfig = ensureNormConfig(project, detectedLanguage);
    const mutateConfig = ensureMutateConfig(project, detectedLanguage);
    const predictionsData = syncPredictionsData(project);

    log(`\n${path.basename(project)}`);
    log(`  protocol: ${protocol.file} ${protocol.action}`);

    if (stampLine) {
      log(stampLine);
    }

    for (const memory of nativeMemory) {
      const detail =
        memory.action === "created"
          ? "created (imports @AGENTS.md)"
          : memory.action === "appended"
            ? "import @AGENTS.md ajouté (contenu conservé)"
            : memory.action === "failed"
              ? "non inscriptible — import @AGENTS.md non ajouté"
              : "importe déjà @AGENTS.md";
      log(`  native memory: ${memory.file} ${detail}`);
    }

    log(`  friction bank: ${traps.length} trap(s)`);
    const guardCreated = `${guard.created.length} file(s) created`;
    const guardRefreshed =
      guard.refreshed.length > 0 ? `, ${guard.refreshed.length} refreshed` : "";
    log(
      `  guard (claude): ${guard.wired ? "hook already wired" : "hook wired"} — ${guardCreated}${guardRefreshed}`,
    );
    if (normHook) {
      const state = normHook.skipped
        ? "settings.json illisible ou de forme inattendue — non modifié"
        : normHook.refreshed
          ? "hook repointed to the current binary"
          : normHook.wired
            ? "hook already wired"
            : "hook wired";
      log(`  norm hook (claude): ${state}`);
    }
    log(
      `  guard (codex): ${guard.codex.skipped ? "customized .codex/config.toml — not touched" : ".codex/config.toml up to date"}`,
    );
    if (openCodeGuard) {
      const rel = normalizePortable(PLUGIN_RELATIVE);
      const state =
        openCodeGuard.status === "skipped"
          ? "plugin personnalisé — laissé intact"
          : openCodeGuard.status === "created"
            ? `${rel} créé`
            : openCodeGuard.status === "upgraded"
              ? `${rel} régénéré`
              : `${rel} inchangé`;
      log(`  opencode guard: ${state}`);
    }
    log(`  dogfood journal: .ai-learn/dogfood.md ${dogfood}`);
    log(`  checkpoint README: checkpoint/README.md ${checkpointReadme}`);
    log(`  .gitignore: ${gitignore}`);
    log(
      `  commit-msg hook: ${commitHook.skipped ? "no .git yet — skipped" : `.githooks/commit-msg ${commitHook.file}, core.hooksPath ${commitHook.hooksPath}`}`,
    );
    log(
      `  norm config: .ai-learn/norm.json ${normConfig.created ? "created" : "already present — not touched"}`,
    );
    log(
      `  mutate config: .ai-learn/mutate.json ${mutateConfig.created ? "created" : "already present — not touched"}`,
    );

    // Story 09.01 — a project no ledger knows (verify's sync failed in a
    // sandbox, or predates the ledgers) is caught up here. Only those: a
    // replay re-reads git/gh signals and walks the sources, too costly to run
    // on every project at every update. Never aborts the remaining projects.
    let ledgerLine;
    try {
      const { missing, unreadable } = ledgerHealth({ dir: project, home });
      if (missing.length === 0) {
        ledgerLine = "  ledgers: à jour";
      } else {
        const ledgers = syncProjectLedgers({ dir: project, home });
        ledgerLine = `  ledgers: ${ledgers.replayed} preuve(s) rejouée(s)`;
        for (const failure of ledgers.failures) {
          ledgerLine += `\n    ${formatSyncFailure(failure)}`;
        }
      }
      if (unreadable.length > 0) {
        ledgerLine += `\n    ⚠ ledger illisible, laissé intact : ${unreadable.join(", ")} — le corriger ou le retirer`;
      }
    } catch (error) {
      ledgerLine = `  ⚠ ledgers non synchronisés : ${error.code || error.message}`;
    }
    log(ledgerLine);

    if (predictionsData.action === "created") {
      log(
        `  predictions data: .ai-learn/predictions.json created${
          predictionsData.hasLegacyEntries
            ? " — docs/plans/predictions.md has existing entries; predictions.json now takes precedence for counting (record new ones with `ai-learn predict`)"
            : ""
        }`,
      );
    } else {
      log(
        "  predictions data: .ai-learn/predictions.json already present — not touched",
      );
    }
  }
}

module.exports = { updateCommand, syncProtocol, syncDogfood };
